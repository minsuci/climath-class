"""1회차 «수와 식의 문법» 전 문항 검산.  실행: python3 verify/lesson01.py"""
from fractions import Fraction as F
import math

chk = []
def c(label, got, want):
    ok = math.isclose(got, want, rel_tol=1e-9) if isinstance(got, float) or isinstance(want, float) else got == want
    chk.append((ok, label, got, want))

# [예제 1] 부호와 거듭제곱
c("예1-1  (-5)*4",   (-5)*4,    -20)
c("예1-2  (-5)*(-4)",(-5)*(-4),  20)
c("예1-3  (-2)^4",   (-2)**4,    16)
c("예1-4  -2^4",     -(2**4),   -16)

# [예제 2] 계산 순서
c("예2-1", 18-4*3, 6); c("예2-2", (18-4)*3, 42)
c("예2-3", 24//4//2, 3); c("예2-4", 5+2*(7-9)**2, 13)

# [연습 1] 부호
for lab, g, w in [("연1-1",-7+12,5), ("연1-2",-7-12,-19), ("연1-3",6-(-9),15),
                  ("연1-4",(-3)*(-6),18), ("연1-5",-48//6,-8),
                  ("연1-6",(-2)*(-3)*(-5),-30), ("연1-7",-(5**2),-25), ("연1-8",(-5)**2,25)]:
    c(lab, g, w)

# [연습 2] 계산 순서
for lab, g, w in [("연2-1",20-3*4,8), ("연2-2",(20-3)*4,68), ("연2-3",36//3*2,24),
                  ("연2-4",36//(3*2),6), ("연2-5",15-7-3,5), ("연2-6",15-(7-3),11),
                  ("연2-7",2+3*(-4)**2,50), ("연2-8",(-2)**3+4*(5-8),-20)]:
    c(lab, g, w)

# [연습 4] 지수
for lab, g, w in [("연4-1",2**3*2**4,128), ("연4-2",(3**2)**3,729), ("연4-3",5**6//5**4,25),
                  ("연4-4",7**0,1), ("연4-5",F(1,2**3),F(1,8))]:
    c(lab, g, w)

# [연습 5] 근호
c("연5-1", math.sqrt(50), 5*math.sqrt(2))
c("연5-2", math.sqrt(8)*math.sqrt(2), 4.0)
c("연5-3", math.sqrt(27)/math.sqrt(3), 3.0)
c("연5-5", math.sqrt(18)-math.sqrt(2), 2*math.sqrt(2))
c("연5-6", 1/math.sqrt(5), math.sqrt(5)/5)
c("연5-8", (3+math.sqrt(2))*(3-math.sqrt(2)), 7.0)

# [통합 A]
c("통A-1", (-3)**2-3**2, 0); c("통A-2", -(4**2)+(-4)**2, 0)
c("통A-3", 24//((-2)**3), -3); c("통A-4", 2**5//2**2*2, 16)
c("통A-5", (-1)**100+(-1)**101, 0)
c("통A-6", math.sqrt(32)+math.sqrt(8), 6*math.sqrt(2))
c("통A-7", (2-math.sqrt(5))*(2+math.sqrt(5)), -1.0)
c("통A-8", (F(1,3)+F(1,9))*9, F(4))

# [통합 B] 식 세우기
c("통B-4  넓이50 한 변", math.sqrt(50), 5*math.sqrt(2))

# [과제 A]
for lab, g, w in [("과A-1",-8+3,-5), ("과A-2",-8-(-3),-5), ("과A-3",(-2)**6,64),
                  ("과A-4",-(2**6),-64), ("과A-5",40//(-5)*2,-16),
                  ("과A-6",6-2*(3-7),14), ("과A-7",3**4//3**2,9)]:
    c(lab, g, w)
c("과A-9",  math.sqrt(75)-math.sqrt(12), 3*math.sqrt(3))
c("과A-10", (1+math.sqrt(3))*(1-math.sqrt(3)), -2.0)

# [과제 B] 식 세우기
c("과B-1  택시 d=5km", 4800+1200*(5-2), 8400)
c("과B-2  0.8*1.1",    0.8*1.1, 0.88)
c("과B-4  겉넓이96 → 부피", 4**3, 64)

# [과제 D] 72의 법칙
print("1.05^10 =", round(1.05**10, 4), "→ 100만 원이", round(100*1.05**10, 1), "만 원")
print("1.06^12 =", round(1.06**12, 4), "→ 100만 원이", round(100*1.06**12, 1), "만 원")

bad = [t for t in chk if not t[0]]
print(f"검산 완료 — {len(chk)}항목 중 불일치 {len(bad)}")
for t in bad:
    print("  X", t)
raise SystemExit(1 if bad else 0)
